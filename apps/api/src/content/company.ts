export function luhnComplete(prefix: string, length: number, rng: Rng): string {
  let body = prefix;
  while (body.length < length - 1) body += String(rng.randint(0, 9));
  let total = 0;
  [...body].reverse().forEach((ch, i) => {
    let d = Number(ch);
    if (i % 2 === 0) {
      d *= 2;
      if (d > 9) d -= 9;
    }
    total += d;
  });
  return body + String((10 - (total % 10)) % 10);
}

function ibanDe(rng: Rng): string {
  let bban = "";
  for (let i = 0; i < 18; i++) bban += String(rng.randint(0, 9));
  const numeric = [...(bban + "DE00")].map((c) => parseInt(c, 36).toString()).join("");
  const check = 98 - Number(BigInt(numeric) % 97n);
  return `DE${pad(check, 2)}${bban}`;
}

function ssn(rng: Rng): string {
  let area = rng.randint(1, 899);
  if (area === 666) area = 667;
  return `${pad(area, 3)}-${pad(rng.randint(1, 99), 2)}-${pad(rng.randint(1, 9999), 4)}`;
}

