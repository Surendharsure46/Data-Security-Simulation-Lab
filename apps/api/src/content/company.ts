export function environmentTemplate(): Json {
  if (cachedTemplate) return structuredClone(cachedTemplate);
  const content = buildContent();
  cachedTemplate = {
    company: COMPANY,
    labels: DEFAULT_LABELS,
    identities: identities(),
    groups: GROUPS,
    assets: ASSETS.map((a) => ({
      key: a[0], name: a[1], asset_type: a[2], data_structure: a[3], system: a[4], location: a[5], department: a[6],
      owner_key: a[7], label_key: a[8], record_count: a[9], size_bytes: a[10], description: a[11], content_sample: content[a[0]] ?? "",
    })),
    grants: GRANTS.map((g) => ({ key: g[0], asset_key: g[1], principal_type: g[2], principal_key: g[3], permission: g[4], justification: g[5] })),
    destinations: DESTINATIONS.map((d) => ({ key: d[0], name: d[1], kind: d[2], domain: d[3], category: d[4], sanctioned: d[5], internal: d[6] })),
    classification_rules: CLASSIFICATION_RULES.map((r) => ({
      key: r[0], name: r[1], detectors: r[2], min_matches: r[3], min_confidence: r[4], recommended_label: r[5] })),
    policies: BASELINE_POLICIES,
  };
  return structuredClone(cachedTemplate);
}
